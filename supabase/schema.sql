-- Tirumala Live Info: minimal public-read snapshot and private push-token registry.
-- Run this file once in Supabase Dashboard -> SQL Editor.

create table if not exists public.live_snapshots (
  id text primary key,
  payload jsonb not null,
  updated_at timestamptz not null default now()
);

alter table public.live_snapshots enable row level security;
revoke all on public.live_snapshots from anon, authenticated;
grant select on public.live_snapshots to anon, authenticated;
grant all on public.live_snapshots to service_role;
drop policy if exists "Anyone can read the latest public information" on public.live_snapshots;
create policy "Anyone can read the latest public information"
  on public.live_snapshots for select to anon, authenticated using (id = 'latest');

create table if not exists public.push_subscriptions (
  id bigint generated by default as identity primary key,
  fcm_token text not null unique,
  created_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now()
);

alter table public.push_subscriptions enable row level security;
revoke all on public.push_subscriptions from anon, authenticated;
grant insert on public.push_subscriptions to anon, authenticated;
grant all on public.push_subscriptions to service_role;
drop policy if exists "Allow browser devices to register a push token" on public.push_subscriptions;
create policy "Allow browser devices to register a push token"
  on public.push_subscriptions for insert to anon, authenticated
  with check (length(fcm_token) between 100 and 4096);

-- No public SELECT policy is created for push_subscriptions. Device tokens remain private.
